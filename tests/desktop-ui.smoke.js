  await page.evaluate(() => { window.__desktopTest.savePath = 'C:\\Exports\\数据表.xlsx' })
  await page.getByRole('button', { name: 'Excel', exact: true }).click()
  await page.waitForFunction(() => window.__desktopTest.exports.length === 1)
  await page.getByRole('tab', { name: '深圳故事.md', exact: true }).click()

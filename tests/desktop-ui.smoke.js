  const text = await source.innerText()
  if (!text.includes('中文快速切换') || !text.startsWith('---\ntitle: \nsubtitle: \n---')) {
    throw new Error(`Rich editor flush or Front Matter preservation failed: ${text}`)
  }
  await source.click()
  await source.press('ControlOrMeta+End')
  await page.keyboard.insertText('\n源码修改')
  await source.press('ControlOrMeta+z')
  if ((await source.innerText()).includes('源码修改')) throw new Error('Source undo failed')

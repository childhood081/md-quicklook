  await page.setViewportSize({ width: 1200, height: 800 })
  await page.getByRole('button', { name: '选择文件', exact: true }).click()
  await page.getByRole('tab', { name: '数据表.md', exact: true }).waitFor()
  if (await page.getByRole('tab').count() !== 2) throw new Error('Expected two document tabs')
  await page.getByRole('tab', { name: '深圳故事.md', exact: true }).click()
  await page.getByRole('button', { name: 'E编辑', exact: true }).click()
  const rich = page.getByRole('textbox')
  await rich.click()
  await rich.press('ControlOrMeta+End')
  await page.keyboard.insertText('中文快速切换')

  await page.evaluate(() => { window.__desktopTest.savePath = 'C:\\Exports\\深圳故事.docx' })
  await page.getByRole('button', { name: 'Word', exact: true }).click()
  await page.waitForFunction(() => window.__desktopTest.exports.length === 2)
  const exportInfo = await page.evaluate(() => ({
    names: window.__desktopTest.saveCalls.map((call) => call.options.defaultPath),
    docs: window.__desktopTest.exports.map((item) => ({ path: item.outputPath, size: item.bytes.length, header: item.bytes.slice(0, 2) })),
  }))
  if (exportInfo.names.join('|') !== '数据表.xlsx|深圳故事.docx') throw new Error('Export filenames do not match the document')
  if (exportInfo.docs[1].header.join(',') !== '80,75') throw new Error('DOCX is not a ZIP package')
  await page.getByRole('button', { name: 'PDF', exact: true }).click()
  await page.waitForFunction(() => window.__desktopTest.prints.length === 1)
  const pdf = await page.evaluate(() => window.__desktopTest.prints[0])
  if (pdf.title !== '深圳故事' || pdf.html.includes('subtitle:') || !pdf.html.includes('中文快速切换') || !pdf.html.includes('源码修改')) {
    throw new Error('PDF filename or latest content is incorrect')
  }
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  if (await page.title() !== 'AI 文档快看') throw new Error('Printing did not restore the application title')
  if (await page.locator('#md-quicklook-print-root').count()) throw new Error('Print DOM was not cleaned up')
  await page.evaluate(() => window.__desktopTest.emit('menu-action', 'file.export_pdf'))
  await page.waitForFunction(() => window.__desktopTest.prints.length === 2)
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')))
  await page.evaluate(() => { window.__desktopTest.savePath = null })
  await page.getByRole('button', { name: 'Word', exact: true }).click()

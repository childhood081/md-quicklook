  if (!(await source.innerText()).includes('源码修改')) throw new Error('Source redo failed')
  await page.getByRole('tab', { name: '数据表.md', exact: true }).click()
  await page.waitForFunction(() => window.__desktopTest.writes.some((item) => item.content.includes('源码修改')))
  const saved = await page.evaluate(() => window.__desktopTest.writes)
